CREATE SCHEMA IF NOT EXISTS core;
CREATE SCHEMA IF NOT EXISTS inventory;

CREATE TABLE IF NOT EXISTS core.users (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(20) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    full_name TEXT NOT NULL,
    is_admin BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_username_length CHECK (char_length(username) >= 3)
);

CREATE TABLE IF NOT EXISTS core.visitor_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visitor_id TEXT NOT NULL,
    visitor_name TEXT NOT NULL,
    contact_info TEXT,
    check_in TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_users_username ON core.users (username);
CREATE INDEX IF NOT EXISTS idx_visitor_log_check_in ON core.visitor_log (check_in DESC);
CREATE INDEX IF NOT EXISTS idx_visitor_log_name ON core.visitor_log USING gin (to_tsvector('spanish', visitor_name));

CREATE TABLE IF NOT EXISTS inventory.books (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_id INT NOT NULL DEFAULT 1,
    isbn TEXT UNIQUE,
    title TEXT NOT NULL,
    author TEXT NOT NULL,
    publisher TEXT NOT NULL,
    publication_year SMALLINT,
    dewey_code TEXT,
    is_braille BOOLEAN NOT NULL DEFAULT FALSE,
    is_audiobook BOOLEAN NOT NULL DEFAULT FALSE,
    classification_system TEXT NOT NULL DEFAULT 'Dewey'
);

CREATE TABLE IF NOT EXISTS inventory.items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id INT NOT NULL,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    shelf_location TEXT NOT NULL,
    entry_date DATE NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT fk_items_book 
        FOREIGN KEY (book_id) 
        REFERENCES inventory.books (id) 
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS inventory.interests (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id INT NOT NULL,
    user_id INT NOT NULL,
    CONSTRAINT uq_interests_book_user UNIQUE (book_id, user_id),
    CONSTRAINT fk_interests_book 
        FOREIGN KEY (book_id) 
        REFERENCES inventory.books (id) 
        ON DELETE CASCADE,
    CONSTRAINT fk_interests_user 
        FOREIGN KEY (user_id) 
        REFERENCES core.users (id) 
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_books_isbn ON inventory.books (isbn);
CREATE INDEX IF NOT EXISTS idx_books_dewey ON inventory.books (dewey_code);
CREATE INDEX IF NOT EXISTS idx_books_title_trgm ON inventory.books (title);
CREATE INDEX IF NOT EXISTS idx_books_author ON inventory.books (author);
CREATE INDEX IF NOT EXISTS idx_items_book_id ON inventory.items (book_id);
CREATE INDEX IF NOT EXISTS idx_items_availability ON inventory.items (is_available);
CREATE INDEX IF NOT EXISTS idx_interests_user_id ON inventory.interests (user_id);
